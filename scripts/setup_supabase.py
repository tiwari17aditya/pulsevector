import os
import sys
import argparse
from supabase import create_client, Client

def setup_supabase(url: str, key: str):
    print("🚀 Initializing Supabase Setup...")
    try:
        supabase: Client = create_client(url, key)
    except Exception as e:
        print(f"❌ Failed to connect to Supabase: {e}")
        sys.exit(1)
        
    bucket_name = "pulse-vector-media"
    
    print(f"1️⃣ Checking for storage bucket '{bucket_name}'...")
    try:
        buckets = supabase.storage.list_buckets()
        bucket_exists = any(b.name == bucket_name for b in buckets)
        
        if not bucket_exists:
            print(f"   Bucket '{bucket_name}' not found. Creating it...")
            supabase.storage.create_bucket(bucket_name, {"public": True})
            print(f"   ✅ Bucket '{bucket_name}' created successfully!")
        else:
            print(f"   ✅ Bucket '{bucket_name}' already exists.")
            
    except Exception as e:
        print(f"⚠️ Error checking/creating bucket: {e}")
        print("   Make sure your SUPABASE_KEY is a 'service_role' key if creation fails.")
        
    print("\n2️⃣ Checking for 'pipeline_runs' table...")
    print("   Note: Supabase API does not support dynamic table creation from the standard client.")
    print("   Please execute the following SQL in your Supabase SQL Editor to create the table:")
    
    sql_script = """
    -- Create the table
    CREATE TABLE IF NOT EXISTS pipeline_runs (
        id bigint generated by default as identity primary key,
        run_date timestamp with time zone not null,
        file_type text not null,
        file_path text not null unique,
        url text not null,
        created_at timestamp with time zone default timezone('utc'::text, now()) not null
    );

    -- Set up Row Level Security (RLS)
    ALTER TABLE pipeline_runs ENABLE ROW LEVEL SECURITY;

    -- Create policies for anonymous reads (optional if you want it public)
    CREATE POLICY "Allow public read access" ON pipeline_runs FOR SELECT USING (true);
    
    -- Create policies for service role inserts/updates
    CREATE POLICY "Allow service role full access" ON pipeline_runs USING (true) WITH CHECK (true);
    """
    
    print("-" * 50)
    print(sql_script)
    print("-" * 50)
    
    print("✅ Setup checks completed!")

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Setup Supabase bucket for Pulse Vector")
    parser.add_argument("--url", help="Supabase Project URL")
    parser.add_argument("--key", help="Supabase API Key (service_role key recommended for setup)")
    
    args = parser.parse_args()
    
    supabase_url = args.url or os.environ.get("SUPABASE_URL")
    supabase_key = args.key or os.environ.get("SUPABASE_KEY")
    
    if not supabase_url or not supabase_key:
        print("❌ Error: Missing Supabase credentials.")
        print("Please provide --url and --key arguments, or set SUPABASE_URL and SUPABASE_KEY environment variables.")
        sys.exit(1)
        
    setup_supabase(supabase_url, supabase_key)
